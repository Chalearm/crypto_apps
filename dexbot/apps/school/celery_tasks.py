# Function Name : _safe_exp
# Purpose       : Safely computes exponential math without throwing 
#                 [Errno 34] Numerical result out of range. Clamps limits to 
#                 prevent Celery worker core dumps.
# ##############################################################################
def _safe_exp(value, clamp_max=700.0, clamp_min=-700.0):
    try:
        if np.isnan(value) or np.isinf(value):
            return 1.0
            
        safe_val = float(np.clip(value, clamp_min, clamp_max))
        return math.exp(safe_val)
    except OverflowError:
        print(f"      ⚠️ [MATH GUARD] Intercepted math.exp() overflow on value: {value}")
        return float('inf') if value > 0 else 0.0
    except Exception as e:
        print(f"      ⚠️ [MATH GUARD] Unexpected math error: {e}")
        return 1.0
 
# ##############################################################################
# Function Name : _evaluate_predictions_safely
# Purpose       : Evaluates Skill DA, RMSE, Sharpe Ratio, CAGR, Max Drawdown, 
#                 and per-asset Skill DA breakdown matrices.
# ##############################################################################
def _evaluate_predictions_safely(
    y_true: np.ndarray, 
    y_pred: np.ndarray, 
    da_ref: float = 0.5, 
    fee_bps: float = 0.0006,
    asset_names: list = None
) -> dict:
    import numpy as np

    ANNUAL_TRADING_DAYS = 365.0

    # 1. Input Sanitization
    y_true = np.nan_to_num(y_true, nan=0.0, posinf=0.15, neginf=-0.15)
    y_pred = np.nan_to_num(y_pred, nan=0.0, posinf=0.15, neginf=-0.15)

    # 2. Extract Non-Overlapping Daily 1-Step Sequences
    if len(y_true.shape) == 3:
        y_true_daily = y_true[:, 0, :]
        y_pred_daily = y_pred[:, 0, :]
    elif len(y_true.shape) == 2:
        y_true_daily = y_true
        y_pred_daily = y_pred
    else:
        y_true_daily = y_true.reshape(-1, 1)
        y_pred_daily = y_pred.reshape(-1, 1)

    # 3. Root Mean Squared Error
    mse = np.mean(np.square(y_true - y_pred))
    rmse = float(np.sqrt(mse))

    # 4. Normalized Skill Directional Accuracy (Overall)
    true_dirs = np.sign(y_true_daily)
    pred_dirs = np.sign(y_pred_daily)
    correct_dirs = np.sum(true_dirs == pred_dirs)
    total_dirs = y_true_daily.size

    da_model = float(correct_dirs / total_dirs) if total_dirs > 0 else da_ref
    skill_da = float((da_model - da_ref) / (1.0 - da_ref))

    # 5. Per-Asset Skill DA Breakdown Matrix
    asset_skills = {}
    num_assets = y_true_daily.shape[-1]
    
    for col_idx in range(num_assets):
        name = asset_names[col_idx] if (asset_names and col_idx < len(asset_names)) else f"Asset_{col_idx}"
        a_true = y_true_daily[:, col_idx]
        a_pred = y_pred_daily[:, col_idx]
        
        a_correct = np.sum(np.sign(a_true) == np.sign(a_pred))
        a_total = a_true.size
        
        a_da = float(a_correct / a_total) if a_total > 0 else da_ref
        a_skill = float((a_da - da_ref) / (1.0 - da_ref))
        
        asset_skills[name] = {
            "baseline": da_ref,
            "model": a_da,
            "skill": a_skill
        }

    # 6. Compute Return Deltas
    if y_true_daily.shape[0] > 1:
        daily_return_deltas = np.diff(y_true_daily, axis=0, prepend=y_true_daily[:1])
    else:
        daily_return_deltas = y_true_daily

    # 7. Positions & Strategy Returns
    positions = np.sign(y_pred_daily)
    position_changes = np.abs(np.diff(positions, axis=0, prepend=positions[:1]))
    trading_costs = position_changes * fee_bps

    gross_returns = positions * np.clip(daily_return_deltas, -0.15, 0.15)
    net_asset_returns = gross_returns - trading_costs
    strategy_returns = np.mean(net_asset_returns, axis=-1)

    mean_ret = float(np.mean(strategy_returns))
    std_ret = float(np.std(strategy_returns, ddof=1))

    # 8. Sharpe Ratio
    epsilon = 1e-6
    if std_ret > epsilon:
        raw_sharpe = (mean_ret / std_ret) * np.sqrt(ANNUAL_TRADING_DAYS)
        sharpe = float(np.clip(raw_sharpe, -5.0, 50.0))
    else:
        sharpe = -5.0 if mean_ret <= 0 else 0.0

    # 9. Maximum Drawdown
    cum_log_returns = np.cumsum(strategy_returns)
    safe_cum_returns = np.clip(cum_log_returns, -700.0, 700.0)
    equity_curve = np.exp(safe_cum_returns)

    running_peak = np.maximum.accumulate(equity_curve)
    drawdowns = (running_peak - equity_curve) / (running_peak + 1e-12)
    drawdowns = np.nan_to_num(drawdowns, nan=0.0, posinf=0.0, neginf=0.0)
    
    max_dd = float(np.max(drawdowns)) if len(drawdowns) > 0 else 0.0

    # 10. CAGR
    num_steps = max(1, len(strategy_returns))
    annualized_log_ret = float(np.sum(strategy_returns)) * (ANNUAL_TRADING_DAYS / num_steps)
    safe_ann_ret = float(np.clip(annualized_log_ret, -5.0, 5.0))
    cagr = float(np.exp(safe_ann_ret) - 1.0)

    return {
        "rmse": rmse,
        "raw_da": da_model,
        "skill_da": skill_da,
        "sharpe": sharpe,
        "cagr": cagr,
        "max_dd": max_dd,
        "asset_skills": asset_skills  # 🟢 POPULATES GA_MASTER BREAKDOWN
    }
