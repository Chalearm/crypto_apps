# Function Name : export_and_plot_task
#
# Path          : apps/school/celery_tasks.py
# Author        : Chalearm Saelim & Gemini
#
# Purpose :
#    Celery task entry-point for post-GA out-of-sample verification and Pareto
#    frontier graph generation/artifact exports. Ingests JSON task payloads,
#    updates Celery's task state with generation-level metadata for cluster
#    telemetry reporting, and delegates plotting execution to the visualization engine.
#
# Inputs :
#    payload_json
#        Type        : dict | str
#        Description : Serialized or unpacked dictionary containing task_type,
#                      run_id, gen_idx, top_chromosomes, master_data, and val_data.
#
# Return :
#    Type        : dict
#    Description : Execution summary containing status, run_id, gen_idx, and total
#                  processed candidate model forecast count.
#
# Complexity :
#    Time  : O(1) task dispatch routing overhead.
#    Space : O(1) RAM allocation prior to worker execution.
#
# Error Cases :
#    - Catches malformed string JSON payloads and returns structured error dictionaries.
#    - Automatically triggers Celery retries (max_retries=1, countdown=5) on unexpected exceptions.
# ##############################################################################
@app.task(name="tasks.export_and_plot_task", bind=True, max_retries=1)
def export_and_plot_task(self, payload_json: dict) -> dict:
    # --------------------------------------------------------------------------
    # 1. PAYLOAD PARSING & ARGUMENT NORMALIZATION
    # --------------------------------------------------------------------------
    if isinstance(payload_json, str):
        try:
            payload_json = json.loads(payload_json)
        except Exception as parse_err:
            logger.error(f"❌ [EXPORT TASK ERROR] Failed parsing JSON payload string: {parse_err}")
            return {"status": "error", "message": f"Invalid JSON payload: {parse_err}"}

    if not isinstance(payload_json, dict):
        payload_json = {}

    task_type = payload_json.get("task_type", "GEN_PLOT")
    run_id = payload_json.get("run_id", "UNKNOWN")
    gen_idx = payload_json.get("gen_idx", 1)

    print("\n" + "⚡" * 40)
    print(f"⚡ [CELERY WORKER INGEST] Ingested export_and_plot_task")
    print(f"   ├── Task Type    : {task_type}")
    print(f"   ├── Run ID       : {run_id}")
    print(f"   ├── Generation   : {gen_idx}")
    print(f"   └── Task ID      : {self.request.id}")
    print("⚡" * 40 + "\n")

    # --------------------------------------------------------------------------
    # 2. TASK ROUTING: POST-GA OOS VERIFICATION
    # --------------------------------------------------------------------------
    if task_type == "POST_GA_OOS":
        from verify_worker import execute_oos_verification
        try:
            return execute_oos_verification(payload_json)
        except Exception as exc:
            logger.warning(f"⚠️ [OOS RETRY] Verification task failed for Run ID {run_id}: {exc}")
            raise self.retry(exc=exc, countdown=5)

    # --------------------------------------------------------------------------
    # 3. TASK STATE PROGRESS PUBLISHING (TELEMETRY BINDING)
    # --------------------------------------------------------------------------
    try:
        self.update_state(
            state="PROGRESS",
            meta={
                "run_id": run_id,
                "gen_idx": gen_idx,
                "current_candidate": "Initializing",
                "candidate_progress": "0/5",
                "display_target": f"Gen {gen_idx} Plots"
            }
        )
        payload_json["celery_task_handle"] = self
    except Exception as state_err:
        logger.warning(f"⚠️ [CELERY STATE WARN] Could not update task progress state: {state_err}")

    # --------------------------------------------------------------------------
    # 4. DEFAULT ROUTE: PARETO PLOTS & MODEL EXPORTS
    # --------------------------------------------------------------------------
