# Function Name : run_fold_training_task
# Purpose       : Celery worker task that trains a candidate model on a CV fold.
#                 Dynamically extracts the chromosome payload (nodes_per_layer,
#                 learning_rate, dropout, batch_size) from ga_master.py and 
#                 delegates execution to the high-performance Native Rust LSTM 
#                 C-Extension (rust_lstm_engine).
# ##############################################################################
@app.task(bind=True, name="tasks.run_fold_training_task", max_retries=2)
def run_fold_training_task(self, payload: dict):
    import time
    start_fold_time = time.time()
    # Safely extract chromosome, Model ID, and Run ID from payload
    chromosome = payload.get('chromosome', {})
    chrom_id = payload.get('chrom_id', chromosome.get('id', 'UNKNOWN_MODEL'))
    fold_idx = payload.get('fold_idx', -1)
    run_id = payload.get('run_id', 'UNKNOWN_RUN')
    
    print("\n" + "═" * 70)
    print(f"🏋️ [FOLD WORKER START] Model: {chrom_id} | Fold: {fold_idx}")
    print("═" * 70)
    
    try:
        # ----------------------------------------------------------------------
        # 1. DYNAMIC GENETIC PARAMETER UNPACKING (FROM GA_MASTER.PY)
        # ----------------------------------------------------------------------
        nodes_per_layer = chromosome.get('nodes_per_layer', chromosome.get('nodes_list', [64]))
        if isinstance(nodes_per_layer, int):
            nodes_per_layer = [nodes_per_layer]
            
        lstm_units = int(nodes_per_layer[0]) if len(nodes_per_layer) > 0 else int(chromosome.get('lstm_units', 64))
        num_layers = len(nodes_per_layer)
        
        lr_val = float(chromosome.get('learning_rate', 0.001))
        epochs_val = int(chromosome.get('epochs', 25))  # 🟢 Dynamic GA Epochs
        batch_val = int(chromosome.get('batch_size', 32))
        dropout_val = float(chromosome.get('dropout_rate', 0.2))

        print(f"      [CHROMOSOME UNPACK] ID: {chrom_id} | Layers: {num_layers} {nodes_per_layer} | "
              f"LR: {lr_val} | Dropout: {dropout_val} | Epochs: {epochs_val} | Batch: {batch_val}")

        # ----------------------------------------------------------------------
        # 2. TENSOR EXTRACTION & FAULT-TOLERANT PATH ROUTING
        # ----------------------------------------------------------------------
        if 'cache_file' in payload:
            cache_path = payload['cache_file']
            
            # Dynamic Path Resolution: Remap absolute paths from Master to Worker
            if not os.path.exists(cache_path):
                app_root = os.path.dirname(os.path.abspath(__file__))
                filename = os.path.basename(cache_path)
                local_cache_path = os.path.join(app_root, "logs", run_id, "cache", filename)
                
                if os.path.exists(local_cache_path):
                    print(f"      [FOLD-STATE 0.5] Path Mismatch Detected. Remapped to local volume: {local_cache_path}")
                    cache_path = local_cache_path
                else:
                    raise FileNotFoundError(
                        f"Cache missing on Worker.\nMaster Path: {payload['cache_file']}\nLocal Path: {local_cache_path}"
                    )
            
            print(f"      [FOLD-STATE 1.0] Loading dataset from disk cache: {cache_path}")
            
            if str(cache_path).endswith('.npz'):
                with np.load(cache_path, allow_pickle=True) as data:
                    files = data.files
                    x_key = next((k for k in ['X_full', 'X', 'x'] if k in files), files[0])
                    y_key = next((k for k in ['y_full', 'y', 'Y'] if k in files), files[1] if len(files)>1 else files[0])
                    X_full = data[x_key]
                    y_full = data[y_key]
            else:
                import pickle
                with open(cache_path, 'rb') as f:
                    data = pickle.load(f)
                    X_full = data.get('X_full', data.get('X', data.get('x')))
                    y_full = data.get('y_full', data.get('y', data.get('Y')))
            
            train_slice = payload.get('train_slice')
            val_slice = payload.get('val_slice')
            
            def extract_slice(tensor, slice_def):
                if isinstance(slice_def, dict) and 'start' in slice_def and 'end' in slice_def:
                    return tensor[slice_def['start']:slice_def['end']]
                elif isinstance(slice_def, (list, tuple)):
                    if len(slice_def) == 2 and isinstance(slice_def[0], int) and isinstance(slice_def[1], int):
                        return tensor[slice_def[0]:slice_def[1]]
                    return tensor[slice_def]
                return tensor

            X_train = np.ascontiguousarray(extract_slice(X_full, train_slice), dtype=np.float32)
            y_train = np.ascontiguousarray(extract_slice(y_full, train_slice), dtype=np.float32)
            X_val = np.ascontiguousarray(extract_slice(X_full, val_slice), dtype=np.float32)
            y_val = np.ascontiguousarray(extract_slice(y_full, val_slice), dtype=np.float32)
            
        else:
            print(f"      [FOLD-STATE 1.0] Loading tensors directly from network payload...")
            raw_x_train = payload.get('x_train', payload.get('X_train', payload.get('train_x')))
            raw_y_train = payload.get('y_train', payload.get('Y_train', payload.get('train_y')))
            raw_x_val = payload.get('x_val', payload.get('X_val', payload.get('val_x')))
            raw_y_val = payload.get('y_val', payload.get('Y_val', payload.get('val_y')))
            
            if raw_x_train is None or raw_y_train is None:
                raise ValueError(f"Missing training tensors! Available Payload Keys: {list(payload.keys())}")
                
            X_train = np.ascontiguousarray(raw_x_train, dtype=np.float32)
            y_train = np.ascontiguousarray(raw_y_train, dtype=np.float32)
            X_val = np.ascontiguousarray(raw_x_val, dtype=np.float32)
            y_val = np.ascontiguousarray(raw_y_val, dtype=np.float32)
            
        print(f"      [FOLD-STATE 1.1] Tensors extracted safely. Training shape: {X_train.shape} | Val shape: {X_val.shape}")

        # ----------------------------------------------------------------------
        # 3. NATIVE RUST C-EXTENSION ENGINE EXECUTION
        # ----------------------------------------------------------------------
        if not RUST_ENGINE_AVAILABLE:
            raise RuntimeError("rust_lstm_engine is required but not imported on this Worker node.")

        print(f"      [FOLD-STATE 2.0] Executing Native Rust C++ LSTM Engine ({num_layers} Layers | Units: {lstm_units})...")

        raw_preds = rust_lstm_engine.train_and_predict(
            x_train_py=X_train,
            y_train_py=y_train,
            x_val_py=X_val,
            lstm_units=lstm_units,
            learning_rate=lr_val,
            epochs=epochs_val,
            _batch_size=batch_val
        )
        print(f"      [FOLD-STATE 2.1] Native Rust C++ LSTM execution complete.")

        # ----------------------------------------------------------------------
        # 4. VALIDATION INFERENCE & PREDICTION CLIPPING
        # ----------------------------------------------------------------------
        print(f"      [FOLD-STATE 3.0] Processing Rust prediction array...")
        
        # Format prediction tensor to match y_val shape
        if len(raw_preds.shape) == 3 and raw_preds.shape[1] == 1:
            raw_preds = raw_preds[:, 0, :]

        # Sanitize and clip predictions to realistic market boundaries (-10% to +10%)
        safe_preds = np.nan_to_num(raw_preds, nan=0.0, posinf=0.15, neginf=-0.15)
        safe_preds = np.clip(safe_preds, -0.15, 0.15)
        
        # Extract target asset names from payload
        target_cols = payload.get('target_cols', [])
        # ----------------------------------------------------------------------
        # 5. METRIC EVALUATION WITH ASSET NAMES
        # ----------------------------------------------------------------------
        print(f"      [FOLD-STATE 4.0] Evaluating performance metrics safely...")
        fold_metrics = _evaluate_predictions_safely(y_val, safe_preds, asset_names=target_cols)
        fold_duration = time.time() - start_fold_time
        print(f"      [FOLD-STATE 5.0] Fold {fold_idx} completed in {fold_duration:.2f}s | RMSE: {fold_metrics.get('rmse', 0.0):.4f}")

        return {
            "status": "SUCCESS",
            "chromosome_id": chrom_id,
            "fold_idx": fold_idx,
            "execution_time_sec": fold_duration,
            "metrics": fold_metrics
        }

    except Exception as err:
        error_trace = traceback.format_exc()
        
        if "MISCONF Redis" in str(err) or "ResponseError" in str(err):
            print(f"\n❌ [REDIS MISCONF ERROR] Redis background save failed on Worker node!")
            print("Fix: redis-cli config set stop-writes-on-bgsave-error no")
            return {"status": "FAILURE", "error": "Redis Background Save Error", "chromosome_id": chrom_id}
            
        print(f"\n❌ [WORKER FATAL CRASH] Model {chrom_id} | Fold {fold_idx} failed!")
        print(f"      └── Error Type: {type(err).__name__}")
        print(f"      └── Message: {err}")
        print(f"      └── Traceback:\n{error_trace}\n")
        
        return {
            "status": "FAILURE",
            "chromosome_id": chrom_id,
            "fold_idx": fold_idx,
            "execution_time_sec": fold_duration,
            "error": str(err)
        }


