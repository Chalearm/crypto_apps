class DexbotHandler(http.server.SimpleHTTPRequestHandler):
    """Serves static files from OUTPUT_DIR. Forwards POST actions to Governance."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=OUTPUT_DIR, **kwargs)

    def _db_connect(self):
        """Lazy PostgreSQL connection for direct DB queries."""
        if not hasattr(self, '_db_conn') or self._db_conn is None or self._db_conn.closed:
            import time
            for retry in range(3):
                try:
                    import psycopg2
                    self._db_conn = psycopg2.connect(
                        host=os.environ.get('DB_HOST', 'db'),
                        port=os.environ.get('DB_PORT', '5432'),
                        user=os.environ.get('DB_USER', 'trader'),
                        password=os.environ.get('DB_PASS', 'secret'),
                        dbname=os.environ.get('DB_NAME', 'traderdb'),
                        connect_timeout=3
                    )
                    break
                except:
                    if retry < 2:
                        time.sleep(1)
                    else:
                        return None
        if not hasattr(self, '_db_conn'):
            return None
        return self._db_conn

    def _db_query(self, query, params=None):
        conn = self._db_connect()
        if not conn:
            raise Exception("Cannot connect to database")
        cur = conn.cursor()
        try:
            if params:
                cur.execute(query, params)
            else:
                cur.execute(query)
            rows = cur.fetchall()
        finally:
            cur.close()
        return rows

    def _db_columns(self, table):
        conn = self._db_connect()
        if not conn:
            return []
        cur = conn.cursor()
        cur.execute(f"SELECT column_name FROM information_schema.columns WHERE table_name='{table}' ORDER BY ordinal_position")
        cols = [r[0] for r in cur.fetchall()]
        cur.close()
        return cols

    def do_GET(self):
        """Handle GET — static files + API proxy + URL remapping."""
        if self.path.startswith("/api/"):
            self.serve_api()
            return

        # URL remapping for new navigation (§101)
        if self.path == "/trading" or self.path.startswith("/trading"):
            self.path = "/portfolio.html"
        elif self.path == "/school" or self.path.startswith("/school"):
            self.path = "/training.html"
        elif self.path == "/" or self.path.endswith("/"):
            self.path = "/index.html"
        elif not os.path.splitext(self.path)[1]:
            candidate = self.path + ".html"
            if os.path.isfile(os.path.join(OUTPUT_DIR, candidate.lstrip("/"))):
                self.path = candidate

        super().do_GET()

    def serve_api(self):
        """Serve cached JSON from output_dir/api/."""
        # /api/verify/balance — SHA256 auth, returns page-visible values
        if self.path.startswith("/api/verify/"):
            self.serve_verify()
            return

        # /api/balance
        if self.path.startswith("/api/balance"):
            data = self._load_balance()
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(json.dumps(data, indent=2).encode())
            return

        # /api/database_tables — list of table names (§87)
        if self.path.startswith("/api/database_tables"):
            fpath = os.path.join(OUTPUT_DIR, "api", "database_tables.json")
            if os.path.isfile(fpath):
                with open(fpath, "r") as f:
                    data = json.load(f)
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Access-Control-Allow-Origin", "*")
                self.end_headers()
                self.wfile.write(json.dumps(data, indent=2).encode())
                return
            # Fallback: query database directly
            try:
                tables = self._db_query("SELECT table_name FROM information_schema.tables WHERE table_schema='public' ORDER BY table_name")
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Access-Control-Allow-Origin", "*")
                self.end_headers()
                self.wfile.write(json.dumps({"tables": [r[0] for r in tables]}, indent=2).encode())
                return
            except Exception as e:
                self.send_error(500, f"DB not available: {e}")

        # /api/database?table=X&rows=N&sort=Y — dynamic DB query (§87)
        if self.path.startswith("/api/database"):
            from urllib.parse import urlparse, parse_qs
            qs = parse_qs(urlparse(self.path).query)
            table = qs.get('table', [None])[0]
            rows_n = int(qs.get('rows', ['5'])[0])
            sort = qs.get('sort', ['newest'])[0]

            # Always query directly — do NOT use cache for dynamic queries
            # because cache ignores rows/sort parameters (bug §87).
            # Only use cache for the default (no query params) table list.
            if not table:
                fpath = os.path.join(OUTPUT_DIR, "api", "database_tables.json")
                if os.path.isfile(fpath):
                    with open(fpath, "r") as f:
                        data = json.load(f)
                    self.send_response(200)
                    self.send_header("Content-Type", "application/json")
                    self.send_header("Access-Control-Allow-Origin", "*")
                    self.end_headers()
                    self.wfile.write(json.dumps(data, indent=2).encode())
                    return

            # Direct SQL query — rows and sort applied correctly
            try:
                order = ""
                if sort == "newest" or sort == "oldest":
                    cols = self._db_columns(table)
                    orderCol = ""
                    for c in ["id", "created_at", "ts", "timestamp"]:
                        if c in cols:
                            orderCol = c
                            break
                    # Fallback: use first column if no standard sort column exists
                    if not orderCol and len(cols) > 0:
                        orderCol = cols[0]
                    if orderCol:
                        dir = "DESC" if sort == "newest" else "ASC"
                        order = f" ORDER BY {orderCol} {dir}"
                rows = self._db_query(f"SELECT * FROM {table}{order} LIMIT {rows_n}")
                cols = self._db_columns(table)
                result = {"columns": cols, "rows": [[str(v) if v is not None else "" for v in r] for r in rows]}
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Access-Control-Allow-Origin", "*")
                self.end_headers()
                self.wfile.write(json.dumps(result, indent=2).encode())
                return
            except Exception as e:
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Access-Control-Allow-Origin", "*")
                self.end_headers()
                self.wfile.write(json.dumps({"columns": [], "rows": [], "note": f"Table not queryable: {e}"}, indent=2).encode())
                return

        api_path = self.path.replace("/api/", "").replace("/", "_") + ".json"
        file_path = os.path.join(OUTPUT_DIR, "api", api_path)

        try:
            with open(file_path, "r") as f:
                data = json.load(f)
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(json.dumps(data, indent=2).encode())
        except FileNotFoundError:
            daemon_file = os.path.join(OUTPUT_DIR, "api", "daemons.json")
            if os.path.isfile(daemon_file):
                with open(daemon_file, "r") as f:
                    data = json.load(f)
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Access-Control-Allow-Origin", "*")
                self.end_headers()
                self.wfile.write(json.dumps(data, indent=2).encode())
            else:
                self.send_error(404, "API endpoint not found")

