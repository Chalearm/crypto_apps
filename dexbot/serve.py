    def _db_connect(self):
        """Lazy PostgreSQL connection for direct DB queries."""
        if not hasattr(self, '_db_conn') or self._db_conn is None or self._db_conn.closed:
            import time
            for retry in range(3):
                try:
                    import psycopg2
                    self._db_conn = psycopg2.connect(
                        host=os.environ.get('DB_HOST', 'db'),
                        port=os.environ.get('DB_PORT', '5432'),
                        user=os.environ.get('DB_USER', 'trader'),
                        password=os.environ.get('DB_PASS', 'secret'),
                        dbname=os.environ.get('DB_NAME', 'traderdb'),
                        connect_timeout=3
                    )
                    break
                except:
                    if retry < 2:
                        time.sleep(1)
                    else:
                        return None
        if not hasattr(self, '_db_conn'):
            return None
        return self._db_conn

    def _db_query(self, query, params=None):
        conn = self._db_connect()
        if not conn:
            raise Exception("Cannot connect to database")
        cur = conn.cursor()
        try:
            if params:
                cur.execute(query, params)
            else:
                cur.execute(query)
            rows = cur.fetchall()
        finally:
            cur.close()
        return rows

    def _db_columns(self, table):
        conn = self._db_connect()
        if not conn:
            return []
        cur = conn.cursor()
        cur.execute(f"SELECT column_name FROM information_schema.columns WHERE table_name='{table}' ORDER BY ordinal_position")
        cols = [r[0] for r in cur.fetchall()]
        cur.close()
        return cols

    def _proxy_crud_to_balance(self, route, body):
        """Try routing a CRUD POST to the balance daemon. Returns True on success."""
        balance_port = os.environ.get("DAEMON_BALANCE_HTTP_PORT", "8085")
        balance_ip = os.environ.get("DAEMON_BALANCE_IP", "127.0.0.1")
        import urllib.request
        target = f"http://{balance_ip}:{balance_port}{route}"
        try:
            req = urllib.request.Request(target, data=body,
                headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=5) as resp:
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Access-Control-Allow-Origin", "*")
                self.end_headers()
                self.wfile.write(resp.read())
                return True
        except Exception as e:
            print(f"[proxy] balance daemon unreachable ({route}): {e}", flush=True)
            return False

